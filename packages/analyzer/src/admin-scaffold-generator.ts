function generateTableFormPage(
  table: TableDefinition,
  isEdit: boolean,
  fw: UiFramework,
): AdminPage {
  const modelName = toPascalCase(table.name);
  const camelModel = toCamelCase(table.name);

  const formFields: Array<{ name: string; type: string; label: string }> = [];
  for (const col of table.columns) {
    if (col.isPrimary && col.isAutoIncrement) continue;
    formFields.push({
      name: col.name,
      type: tableInputType(col.type),
      label: col.comment ?? fieldLabel(col.name),
    });
  }

  const pageName = isEdit ? `${modelName}EditPage` : `${modelName}NewPage`;
  const pageTitle = isEdit ? `${modelName} 編集` : `${modelName} 新規作成`;
  const apiMethod = isEdit ? "PUT" : "POST";
  const apiResource = pluralize(table.name);
  const apiUrl = isEdit
    ? `\`/api/${apiResource}/\${id}\``
    : `"/api/${apiResource}"`;

  const editFetch = isEdit
    ? `
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    fetch(\`/api/${pluralize(table.name)}/\${id}\`)
      .then((res) => res.json())
      .then((data) => {
        setForm(data);
        setLoading(false);
      })
      .catch(() => setLoading(false));
  }, [id]);
`
    : "";

  const paramsLine = isEdit
    ? `\n  const params = useParams();\n  const id = params.id;`
    : "";

  const redirectPath = `/${pluralize(table.name)}`;

  const jsxPreamble = `"use client";

import { useState${isEdit ? ", useEffect" : ""} } from "react";
import { useRouter${isEdit ? ", useParams" : ""} } from "next/navigation";

export default function ${pageName}() {
  const router = useRouter();${paramsLine}
  const [form, setForm] = useState<Record<string, string | number | boolean>>({});
  const [error, setError] = useState<string | null>(null);
  const [submitting, setSubmitting] = useState(false);${editFetch}

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setSubmitting(true);
    setError(null);

    try {
      const res = await fetch(${apiUrl}, {
        method: "${apiMethod}",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(form),
      });

      if (!res.ok) {
        const data = await res.json();
        throw new Error(data.error ?? "保存に失敗しました");
      }

      router.push("${redirectPath}");
      router.refresh();
    } catch (err) {
      setError(err instanceof Error ? err.message : "エラーが発生しました");
    } finally {
      setSubmitting(false);
    }
  };

`;

  let content: string;
  if (fw === "tailwind") {
    content = jsxPreamble + `  return (
    <div className="p-6 max-w-3xl">
      <h1 className="text-2xl font-bold mb-6">${pageTitle}</h1>

      {error && (
        <div className="p-3 bg-red-50 text-red-600 rounded-md mb-4">
          {error}
        </div>
      )}

      <form onSubmit={handleSubmit}>
        <div className="grid gap-4 max-w-2xl">
${formFields
  .map(
    (f) => `          <div className="flex flex-col gap-1">
            <label className="text-sm font-medium">
              ${f.label}
            </label>
            <input
              type="${f.type}"
              value={String(${recordAccess("form", f.name)} ?? "")}
              onChange={(e) => setForm({ ...form, ${recordUpdate(f.name, f.type === "number" ? "Number(e.target.value)" : f.type === "checkbox" ? "e.target.checked" : "e.target.value")} })}
              className="px-3 py-2 border border-gray-300 rounded-md focus:ring-2 focus:ring-blue-500 focus:border-blue-500"
            />
          </div>`,
  )
  .join("\n")}
        </div>

        <div className="flex gap-3 mt-6">
          <button
            type="submit"
            disabled={submitting}
            className="px-4 py-2 bg-blue-600 text-white rounded-md hover:bg-blue-700 disabled:opacity-50"
          >
            {submitting ? "保存中..." : "保存"}
          </button>
          <button
            type="button"
            onClick={() => router.back()}
            className="px-4 py-2 bg-gray-100 text-gray-700 border border-gray-300 rounded-md hover:bg-gray-200"
          >
            キャンセル
          </button>
        </div>
      </form>
    </div>
  );
}
`;
  } else {
    content = jsxPreamble + `  return (
    <div className="wp-admin-wrap">
      <h1 className="wp-admin-title">${pageTitle}</h1>

      {error && (
        <div className="wp-notice wp-notice-error">
          <p>{error}</p>
        </div>
      )}

      <form onSubmit={handleSubmit}>
${formFields
  .map(
    (f) => `        <div className="wp-form-field">
          <label>
            ${f.label}
          </label>
          <input
            className="wp-form-input"
            type="${f.type}"
            value={String(${recordAccess("form", f.name)} ?? "")}
            onChange={(e) => setForm({ ...form, ${recordUpdate(f.name, f.type === "number" ? "Number(e.target.value)" : f.type === "checkbox" ? "e.target.checked" : "e.target.value")} })}
          />
        </div>`,
  )
  .join("\n")}

        <div style={{ display: "flex", gap: "12px", marginTop: "24px" }}>
          <button
            type="submit"
            disabled={submitting}
            className="wp-button wp-button-primary"
          >
            {submitting ? "保存中..." : "保存"}{submitting && <span className="wp-spinner" />}
          </button>
          <button
            type="button"
            onClick={() => router.back()}
            className="wp-button"
          >
            キャンセル
          </button>
        </div>
      </form>
    </div>
  );
}
`;
  }

  // Use pluralized path to match list page (generateTableListPage uses pluralize)
  const resource = pluralize(table.name);
  const path = isEdit
    ? `app/(admin)/${resource}/[id]/edit/page.tsx`
    : `app/(admin)/${resource}/new/page.tsx`;

  return {
    path,
    content,
    type: "form" as const,
  };
}

// ── Public API ──

export function generateAdminScaffold(
  analyses: PhpFileAnalysis[],
  tables: TableDefinition[],
  options?: AdminScaffoldOptions,
): AdminPage[] {
  const fw: UiFramework = options?.uiFramework ?? "plain";
  const pages: AdminPage[] = [];
  const processedPaths = new Set<string>();

  // Group analyses by resource for finding related form analysis
  const analysisByFile = new Map<string, PhpFileAnalysis>();
  for (const a of analyses) {
    analysisByFile.set(a.fileName, a);
  }

  // Process each PHP template file
  for (const analysis of analyses) {
    const mapping = mapPhpToRoute(analysis.fileName);
    if (!mapping) continue;
    if (processedPaths.has(mapping.path)) continue;

    processedPaths.add(mapping.path);
    const table = findTableForResource(mapping.resource, tables);

    let content: string;
    switch (mapping.type) {
      case "list":
        content = generateListPage(mapping.resource, table, analyses, fw);
        break;
      case "form": {
        const isEdit = mapping.path.includes("[id]") && !mapping.path.includes("copy");
        content = generateFormPage(mapping.resource, table, analysis, isEdit, fw);
        break;
      }
      case "detail":
        content = generateDetailPage(mapping.resource, table, fw);
        break;
      default:
        continue;
    }

    pages.push({ path: mapping.path, content, type: mapping.type });
  }

  // Add table-driven CRUD pages — fill gaps for all tables
  if (tables.length > 0) {
    const existingPaths = new Set(pages.map((p) => p.path));

    // Helper: check if path exists in singular or plural form
    const hasPath = (pattern: string) => {
      return existingPaths.has(pattern);
    };

    for (const table of tables) {
      const s = table.name;           // singular (table name)
      const p = pluralize(s);         // plural
      const pre = "app/(admin)/";

      // Composite-key tables (no single isPrimary and no "id" column) cannot
      // use findUnique({ where: { id } }) — skip detail/edit/new and keep
      // only the list page for operational visibility.
      const hasSinglePk =
        table.columns.some(c => c.isPrimary) ||
        table.columns.some(c => c.name === "id");

      // List page
      if (!hasPath(`${pre}${s}/page.tsx`) && !hasPath(`${pre}${p}/page.tsx`)) {
        pages.push(generateTableListPage(table, fw, hasSinglePk));
        existingPaths.add(`${pre}${s}/page.tsx`);
      }

      if (!hasSinglePk) continue;

      // Detail page (singular only — PHP form pages at plural/[id] are NOT detail)
      if (!hasPath(`${pre}${s}/[id]/page.tsx`)) {
        pages.push(generateTableDetailPage(table, fw));
        existingPaths.add(`${pre}${s}/[id]/page.tsx`);
      }

      // Edit page
      if (!hasPath(`${pre}${s}/[id]/edit/page.tsx`) && !hasPath(`${pre}${p}/[id]/edit/page.tsx`)) {
        pages.push(generateTableFormPage(table, true, fw));
        existingPaths.add(`${pre}${s}/[id]/edit/page.tsx`);
      }

      // New page
      if (!hasPath(`${pre}${s}/new/page.tsx`) && !hasPath(`${pre}${p}/new/page.tsx`)) {
        pages.push(generateTableFormPage(table, false, fw));
        existingPaths.add(`${pre}${s}/new/page.tsx`);
      }
    }
  }

  // Generate globals.css
  pages.push({
    path: "app/globals.css",
    content: generateGlobalsCss(),
    type: "dashboard" as const,
  });

  // Generate admin layout
  pages.push({
    path: "app/(admin)/layout.tsx",
    content: generateAdminLayout(pages, tables, fw, options?.requireAuth ?? false),
    type: "dashboard",
  });

  // Generate dashboard page
  pages.push({
    path: "app/(admin)/page.tsx",
    content: generateDashboardPage(tables, fw),
    type: "dashboard",
  });

  return pages;
}
