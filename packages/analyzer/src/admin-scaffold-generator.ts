function generateFormFieldJsx(f: import("./php-analyzer.js").FormField, index: number): string {
  if (f.type === "hidden") return "";

  if (f.type === "select" && f.options) {
    const opts = f.options
      .map((o) => `              <option value="${o.value}">${o.label}</option>`)
      .join("\n");
    return `        <div className="wp-form-field">
          <label>
            ${f.label}
          </label>
          <select
            className="wp-form-select"
            value={String(${recordAccess("form", f.name)} ?? "")}
            onChange={(e) => setForm({ ...form, ${recordUpdate(f.name, "e.target.value")} })}
          >
            <option value="">選択してください</option>
${opts}
          </select>
        </div>`;
  }

  if (f.type === "textarea") {
    return `        <div className="wp-form-field">
          <label>
            ${f.label}
          </label>
          <textarea
            className="wp-form-textarea"
            rows={5}
            value={String(${recordAccess("form", f.name)} ?? "")}
            onChange={(e) => setForm({ ...form, ${recordUpdate(f.name, "e.target.value")} })}
          />
        </div>`;
  }

  if (f.type === "file") {
    return `        <div className="wp-form-field">
          <label>
            ${f.label}
          </label>
          <input
            type="file"${f.accept ? `\n            accept="${f.accept}"` : ""}
            onChange={(e) => setFile(e.target.files?.[0] ?? null)}
          />
        </div>`;
  }

  const inputType = f.type === "datetime-local" || f.type === "date" || f.type === "url"
    ? f.type
    : f.type === "number" ? "number" : "text";

  const valueCoerce = f.type === "number"
    ? "Number(e.target.value)"
    : "e.target.value";

  return `        <div className="wp-form-field">
          <label>
            ${f.label}
          </label>
          <input
            className="wp-form-input"
            type="${inputType}"
            value={String(${recordAccess("form", f.name)} ?? "")}
            onChange={(e) => setForm({ ...form, ${recordUpdate(f.name, valueCoerce)} })}${f.required ? '\n            required' : ""}${f.placeholder ? `\n            placeholder="${f.placeholder}"` : ""}
          />
        </div>`;
}

